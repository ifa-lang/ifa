use crate::error::KoriError;
use serde::{Deserialize, Serialize};
use std::fs;
use std::path::Path;

/// Canonical deterministic lockfile representation (`kori.lock`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Lockfile {
    pub version: u32,
    #[serde(rename = "package", default)]
    pub packages: Vec<LockedPackage>,
}

/// Pinned dependency record in the lockfile.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    pub source: String,
    pub checksum: Option<String>,
    #[serde(default)]
    pub dependencies: Vec<String>,
}

impl Default for Lockfile {
    fn default() -> Self {
        Self {
            version: 1,
            packages: Vec::new(),
        }
    }
}

impl std::str::FromStr for Lockfile {
    type Err = KoriError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        toml::from_str(s).map_err(|e| KoriError::Lockfile(e.to_string()))
    }
}

impl Lockfile {
    /// Read and parse a `kori.lock` file from disk.
    pub fn from_file(path: &Path) -> Result<Self, KoriError> {
        let content = fs::read_to_string(path)?;
        content.parse()
    }

    /// Serialize the lockfile to canonical sorted TOML format.
    pub fn to_string_pretty(&mut self) -> Result<String, KoriError> {
        // Sort packages deterministically by name and version
        self.packages
            .sort_by(|a, b| a.name.cmp(&b.name).then_with(|| a.version.cmp(&b.version)));
        for pkg in &mut self.packages {
            pkg.dependencies.sort();
        }

        let header = "# This file is automatically generated by Kori.\n# Manual editing is not recommended to preserve deterministic build integrity.\n\n";
        let body = toml::to_string_pretty(self).map_err(|e| KoriError::Lockfile(e.to_string()))?;
        Ok(format!("{}{}", header, body))
    }

    /// Save the lockfile to disk atomically.
    pub fn save(&mut self, path: &Path) -> Result<(), KoriError> {
        let content = self.to_string_pretty()?;
        fs::write(path, content)?;
        Ok(())
    }

    /// Find a locked package by name.
    pub fn find_package(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }

    /// Check if a package with specific name and version exists in lockfile.
    pub fn contains_package(&self, name: &str, version: &str) -> bool {
        self.packages
            .iter()
            .any(|p| p.name == name && p.version == version)
    }

    /// Verify BLAKE3 checksum for a locked package.
    /// Returns Ok(true) if matched, Ok(false) if no checksum was recorded,
    /// or Err(KoriError::ChecksumMismatch) if corrupted/tampered.
    pub fn verify_package_checksum(&self, name: &str, calculated: &str) -> Result<bool, KoriError> {
        if let Some(pkg) = self.find_package(name) {
            if let Some(ref expected) = pkg.checksum {
                if expected == calculated {
                    return Ok(true);
                } else {
                    return Err(KoriError::ChecksumMismatch {
                        package: name.to_string(),
                        expected: expected.clone(),
                        calculated: calculated.to_string(),
                    });
                }
            }
        }
        Ok(false)
    }

    /// Remove a package from the lockfile by name.
    pub fn remove_package(&mut self, name: &str) -> bool {
        if let Some(pos) = self.packages.iter().position(|p| p.name == name) {
            self.packages.remove(pos);
            true
        } else {
            false
        }
    }

    /// Return sorted list of all locked package names.
    pub fn package_names(&self) -> Vec<String> {
        let mut names: Vec<String> = self.packages.iter().map(|p| p.name.clone()).collect();
        names.sort();
        names
    }

    /// Insert or update a package entry in the lockfile.
    pub fn update_package(&mut self, pkg: LockedPackage) {
        if let Some(pos) = self.packages.iter().position(|p| p.name == pkg.name) {
            self.packages[pos] = pkg;
        } else {
            self.packages.push(pkg);
        }
    }
}
