use crate::error::KoriError;
use crate::manifest::FfiConfig;
use ifa_fir::{FirModule, FirType};
use ifa_sema::types::{FloatType, IntType};
use ifa_span::INTERNER;
use std::fs;
use std::path::{Path, PathBuf};

/// FFI exported function signature metadata extracted from FIR/AST.
#[derive(Debug, Clone)]
pub struct ExportedFunction {
    pub name: String,
    pub is_strict: bool,
    pub params: Vec<ExportedParam>,
    pub return_type: FirType,
}

#[derive(Debug, Clone)]
pub struct ExportedParam {
    pub name: String,
    pub ty: FirType,
}

/// Generator for C-ABI headers (.h) and PHP 8.4+ / Symfony 8.1 FFI service bridges.
pub struct FfiBridgeGenerator {
    package_name: String,
    config: FfiConfig,
}

impl FfiBridgeGenerator {
    /// Create a new FFI bridge generator for a given package and configuration.
    pub fn new(package_name: &str, config: FfiConfig) -> Self {
        Self {
            package_name: package_name.to_string(),
            config,
        }
    }

    /// Extract all public C-ABI exported functions (`pub extern "C" [strict] fn`) from a FIR module.
    pub fn extract_exported_functions(module: &FirModule) -> Vec<ExportedFunction> {
        let mut exports = Vec::new();

        for func in &module.functions {
            if func.is_pub && func.is_extern.as_deref() == Some("C") {
                let name = INTERNER.resolve(&func.name);
                let params = func
                    .params
                    .iter()
                    .map(|p| {
                        let p_name = INTERNER.resolve(&p.name);
                        ExportedParam {
                            name: p_name,
                            ty: p.ty.clone(),
                        }
                    })
                    .collect();

                exports.push(ExportedFunction {
                    name,
                    is_strict: func.is_strict,
                    params,
                    return_type: func.ret_ty.clone(),
                });
            }
        }

        exports
    }

    /// Generate the canonical C-ABI header definition file content.
    pub fn generate_c_header(&self, functions: &[ExportedFunction]) -> String {
        let guard_name = format!("{}_H", self.package_name.to_uppercase().replace('-', "_"));
        let mut out = String::new();

        out.push_str("/**\n");
        out.push_str(&format!(
            " * @file {}.h\n",
            self.package_name.replace('-', "_")
        ));
        out.push_str(&format!(
            " * @brief IFA C-ABI Native Interface for `{}`\n",
            self.package_name
        ));
        out.push_str(
            " * Automatically generated by Kori for high-performance C, PHP 8.4+ & Symfony 8.1 FFI.\n",
        );
        out.push_str(" */\n\n");

        out.push_str(&format!("#ifndef {}\n", guard_name));
        out.push_str(&format!("#define {}\n\n", guard_name));

        out.push_str("#include <stdint.h>\n");
        out.push_str("#include <stddef.h>\n");
        out.push_str("#include <stdbool.h>\n");
        out.push_str("#include \"ifa_runtime.h\"\n\n");

        out.push_str("#ifdef __cplusplus\n");
        out.push_str("extern \"C\" {\n");
        out.push_str("#endif\n\n");

        if functions.is_empty() {
            out.push_str("/* No public extern \"C\" functions exported in this module */\n\n");
        } else {
            for func in functions {
                out.push_str("/**\n");
                out.push_str(&format!(" * @brief Native IFA export `{}`\n", func.name));
                if func.is_strict {
                    out.push_str(" * @note Deterministic strict execution (pure evaluation).\n");
                }
                out.push_str(" */\n");

                let ret_str = fir_type_to_c(&func.return_type);
                out.push_str(&format!("{} {}(", ret_str, func.name));

                if func.params.is_empty() {
                    out.push_str("void");
                } else {
                    let params_str: Vec<String> = func
                        .params
                        .iter()
                        .map(|p| format!("{} {}", fir_type_to_c(&p.ty), p.name))
                        .collect();
                    out.push_str(&params_str.join(", "));
                }

                out.push_str(");\n\n");
            }
        }

        out.push_str("#ifdef __cplusplus\n");
        out.push_str("}\n");
        out.push_str("#endif\n\n");

        out.push_str(&format!("#endif /* {} */\n", guard_name));
        out
    }

    /// Generate PHP 8.4+ / Symfony 8.1 FFI bridge class content.
    pub fn generate_php_class(
        &self,
        class_name: &str,
        functions: &[ExportedFunction],
        header_rel_path: &str,
        lib_rel_path: &str,
    ) -> String {
        let mut out = String::new();

        out.push_str("<?php\n\n");
        out.push_str("declare(strict_types=1);\n\n");
        out.push_str(&format!("namespace {};\n\n", self.config.php_namespace));

        out.push_str("use FFI;\n");
        out.push_str("use RuntimeException;\n\n");

        out.push_str("/**\n");
        out.push_str(&format!(
            " * Deterministic Native Bridge for `{}`.\n",
            self.package_name
        ));
        out.push_str(" * Built for PHP 8.4+ and Symfony 8.1 FFI integration.\n");
        out.push_str(" */\n");
        out.push_str(&format!("final class {}\n", class_name));
        out.push_str("{\n");
        out.push_str("    private FFI $ffi;\n");
        out.push_str("    private static ?FFI $preloadedFfi = null;\n\n");

        // Embedded C declarations for direct FFI::cdef initialization without external header dependencies
        out.push_str("    private const CDEF = <<< 'CDEF_BLOCK'\n");
        out.push_str("typedef long int64_t;\n");
        out.push_str("typedef unsigned long uint64_t;\n");
        out.push_str("typedef int int32_t;\n");
        out.push_str("typedef unsigned int uint32_t;\n");
        out.push_str("typedef short int16_t;\n");
        out.push_str("typedef unsigned short uint16_t;\n");
        out.push_str("typedef signed char int8_t;\n");
        out.push_str("typedef unsigned char uint8_t;\n");
        out.push_str("typedef _Bool bool;\n\n");

        for func in functions {
            let ret_str = fir_type_to_c(&func.return_type);
            out.push_str(&format!("{} {}(", ret_str, func.name));
            if func.params.is_empty() {
                out.push_str("void");
            } else {
                let params_str: Vec<String> = func
                    .params
                    .iter()
                    .map(|p| format!("{} {}", fir_type_to_c(&p.ty), p.name))
                    .collect();
                out.push_str(&params_str.join(", "));
            }
            out.push_str(");\n");
        }
        out.push_str("CDEF_BLOCK;\n\n");

        // Constructor
        out.push_str("    public function __construct(?string $libraryPath = null, ?string $headerPath = null)\n");
        out.push_str("    {\n");
        out.push_str("        if (self::$preloadedFfi !== null) {\n");
        out.push_str("            $this->ffi = self::$preloadedFfi;\n");
        out.push_str("            return;\n");
        out.push_str("        }\n\n");
        out.push_str("        $lib = $libraryPath ?? self::defaultLibraryPath();\n");
        out.push_str("        if (!file_exists($lib)) {\n");
        out.push_str("            throw new RuntimeException(sprintf('IFA native shared library not found at: %s', $lib));\n");
        out.push_str("        }\n\n");
        out.push_str("        $cdef = self::CDEF;\n");
        out.push_str("        if ($headerPath !== null) {\n");
        out.push_str("            if (!file_exists($headerPath)) {\n");
        out.push_str("                throw new RuntimeException(sprintf('IFA C-ABI header definition not found at: %s', $headerPath));\n");
        out.push_str("            }\n");
        out.push_str("            $rawHeader = file_get_contents($headerPath);\n");
        out.push_str("            if ($rawHeader === false) {\n");
        out.push_str("                throw new RuntimeException(sprintf('Failed to read IFA C-ABI header at: %s', $headerPath));\n");
        out.push_str("            }\n");
        out.push_str("            $cdef = self::sanitizeCdef($rawHeader);\n");
        out.push_str("        }\n\n");
        out.push_str("        $this->ffi = FFI::cdef($cdef, $lib);\n");
        out.push_str("    }\n\n");

        // Sanitize helper
        out.push_str("    /**\n");
        out.push_str(
            "     * Sanitize a C header for PHP FFI parser by stripping preprocessor directives\n",
        );
        out.push_str("     * and C++ linkage declarations.\n");
        out.push_str("     */\n");
        out.push_str("    public static function sanitizeCdef(string $header): string\n");
        out.push_str("    {\n");
        out.push_str("        $clean = preg_replace('/^\\s*#.*$/m', '', $header) ?? $header;\n");
        out.push_str(
            "        $clean = str_replace(['extern \"C\" {', 'extern \"C\"'], '', $clean);\n",
        );
        out.push_str("        $clean = preg_replace('/^\\s*\\}\\s*$/m', '', $clean) ?? $clean;\n");
        out.push_str("        return \"typedef long int64_t;\\ntypedef unsigned long uint64_t;\\ntypedef int int32_t;\\ntypedef unsigned int uint32_t;\\ntypedef short int16_t;\\ntypedef unsigned short uint16_t;\\ntypedef signed char int8_t;\\ntypedef unsigned char uint8_t;\\ntypedef _Bool bool;\\n\" . $clean;\n");
        out.push_str("    }\n\n");

        // Preload support
        out.push_str("    /**\n");
        out.push_str("     * Bind a preloaded FFI instance for zero-overhead execution in opcache.preload.\n");
        out.push_str("     */\n");
        out.push_str("    public static function setPreloadedInstance(FFI $ffi): void\n");
        out.push_str("    {\n");
        out.push_str("        self::$preloadedFfi = $ffi;\n");
        out.push_str("    }\n\n");

        // Default path helpers
        out.push_str("    public static function defaultLibraryPath(): string\n");
        out.push_str("    {\n");
        out.push_str(&format!(
            "        return __DIR__ . '/{}';\n",
            lib_rel_path.trim_start_matches('/')
        ));
        out.push_str("    }\n\n");

        out.push_str("    public static function defaultHeaderPath(): string\n");
        out.push_str("    {\n");
        out.push_str(&format!(
            "        return __DIR__ . '/{}';\n",
            header_rel_path.trim_start_matches('/')
        ));
        out.push_str("    }\n\n");

        // Methods for each exported function
        for func in functions {
            let php_ret = fir_type_to_php(&func.return_type);
            let params_def: Vec<String> = func
                .params
                .iter()
                .map(|p| format!("{} ${}", fir_type_to_php(&p.ty), p.name))
                .collect();
            let args_call: Vec<String> =
                func.params.iter().map(|p| format!("${}", p.name)).collect();

            out.push_str(&format!(
                "    public function {}({}): {}\n",
                func.name,
                params_def.join(", "),
                php_ret
            ));
            out.push_str("    {\n");
            if matches!(func.return_type, FirType::ErrorUnion { .. }) {
                out.push_str(&format!(
                    "        $res = $this->ffi->{}({});\n",
                    func.name,
                    args_call.join(", ")
                ));
                out.push_str("        if ($res->status !== 0) {\n");
                out.push_str(&format!(
                    "            throw new \\RuntimeException(sprintf('IFA native execution error code %d in %s', $res->status, '{}'));\n",
                    func.name
                ));
                out.push_str("        }\n");
                if php_ret == "bool" {
                    out.push_str("        return (bool) $res->value;\n");
                } else if php_ret == "int" {
                    out.push_str("        return (int) $res->value;\n");
                } else if php_ret == "float" {
                    out.push_str("        return (float) $res->value;\n");
                } else if php_ret == "string" {
                    out.push_str("        return (string) $res->value;\n");
                } else if php_ret == "void" {
                    // void return
                } else {
                    out.push_str("        return $res->value;\n");
                }
            } else if func.return_type == FirType::Unit {
                out.push_str(&format!(
                    "        $this->ffi->{}({});\n",
                    func.name,
                    args_call.join(", ")
                ));
            } else {
                let cast_prefix = match php_ret {
                    "bool" => "(bool) ",
                    "int" => "(int) ",
                    "float" => "(float) ",
                    "string" => "(string) ",
                    _ => "",
                };
                out.push_str(&format!(
                    "        return {}$this->ffi->{}({});\n",
                    cast_prefix,
                    func.name,
                    args_call.join(", ")
                ));
            }
            out.push_str("    }\n\n");
        }

        out.push_str("}\n");
        out
    }

    /// Emit both C header and PHP bridge file to the target output directory.
    pub fn emit_bindings(
        &self,
        functions: &[ExportedFunction],
        output_dir: &Path,
        shared_lib_filename: &str,
    ) -> Result<(PathBuf, PathBuf), KoriError> {
        fs::create_dir_all(output_dir)?;

        let header_filename = format!("{}.h", self.package_name.replace('-', "_"));
        let header_path = output_dir.join(&header_filename);
        let header_content = self.generate_c_header(functions);
        fs::write(&header_path, header_content)?;

        let class_name = self
            .config
            .php_class_name
            .clone()
            .unwrap_or_else(|| to_pascal_case(&self.package_name) + "Bridge");
        let php_filename = format!("{}.php", class_name);
        let php_path = output_dir.join(&php_filename);

        let php_content = self.generate_php_class(
            &class_name,
            functions,
            &header_filename,
            shared_lib_filename,
        );
        fs::write(&php_path, php_content)?;

        Ok((header_path, php_path))
    }
}

/// Convert FIR type to its standard C-ABI representation.
pub fn fir_type_to_c(ty: &FirType) -> &'static str {
    match ty {
        FirType::Unit => "void",
        FirType::Bool => "bool",
        FirType::Int(IntType::I8) => "int8_t",
        FirType::Int(IntType::I16) => "int16_t",
        FirType::Int(IntType::I32) => "int32_t",
        FirType::Int(IntType::I64) | FirType::Int(IntType::ISize) => "int64_t",
        FirType::Int(IntType::U8) => "uint8_t",
        FirType::Int(IntType::U16) => "uint16_t",
        FirType::Int(IntType::U32) => "uint32_t",
        FirType::Int(IntType::U64) | FirType::Int(IntType::USize) => "uint64_t",
        FirType::Float(FloatType::F32) => "float",
        FirType::Float(FloatType::F64) => "double",
        FirType::Char => "char",
        FirType::Str => "const char*",
        FirType::String => "const char*",
        FirType::Pointer(_) => "void*",
        FirType::GenerationalRef(_) => "ifa_gen_ref_t",
        FirType::Struct(..) => "void*",
        FirType::ErrorUnion { .. } => "ifa_error_union_t*",
        _ => "void*",
    }
}

/// Convert FIR type to its strict PHP 8.4+ type hint.
pub fn fir_type_to_php(ty: &FirType) -> &'static str {
    match ty {
        FirType::Unit => "void",
        FirType::Bool => "bool",
        FirType::Int(_) => "int",
        FirType::Float(_) => "float",
        FirType::Char | FirType::Str | FirType::String => "string",
        FirType::Pointer(_) => "\\FFI\\CData",
        FirType::GenerationalRef(_) => "\\FFI\\CData",
        FirType::Struct(..) => "\\FFI\\CData",
        FirType::ErrorUnion { ok, .. } => fir_type_to_php(ok),
        _ => "mixed",
    }
}

fn to_pascal_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;

    for c in s.chars() {
        if c == '-' || c == '_' {
            capitalize_next = true;
        } else if capitalize_next {
            result.extend(c.to_uppercase());
            capitalize_next = false;
        } else {
            result.push(c);
        }
    }

    result
}
